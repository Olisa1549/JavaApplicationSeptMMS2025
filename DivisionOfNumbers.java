public class DivisionOfNumbers {
	public static void main (String[] args) {
		
		int num1 = 22;
		int num2 = 70;
		int num3 = 80;
		int num4 = 6;
		int num5 = 31;
		
		int divide = num1 / num2 / num3 / num4 / num5;
		
		System.out.printf("The division of %d,%d,%d,%d,%d is %d",num1,num2,num3,num4,num5,divide);
	
	}
}